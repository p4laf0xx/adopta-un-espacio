const selectorIdioma = document.getElementById("selector-idioma");

const idiomas = {
    es: 0,
    en: 0,
    fr: 1,
    de: 2
};

function traducirPagina(idioma) {

    document.documentElement.lang = idioma;

    document.querySelectorAll("[data-i18n]").forEach(elemento => {

        const clave = elemento.getAttribute("data-i18n");

        if (idioma === "es") {
            elemento.textContent = clave;
        } else if (traducciones[clave]) {
            elemento.textContent = traducciones[clave][idiomas[idioma]];
        }

    });

    document.querySelectorAll("[data-placeholder]").forEach(elemento => {

        const clave = elemento.getAttribute("data-placeholder");

        if (idioma === "es") {
            elemento.placeholder = clave;
        } else if (traducciones[clave]) {
            elemento.placeholder = traducciones[clave][idiomas[idioma]];
        }

    });

    localStorage.setItem("idiomaAdoptaEspacio", idioma);

    if (selectorIdioma) {
        selectorIdioma.value = idioma;
    }
}


// ======================================
// GUARDAR IDIOMA SELECCIONADO
// ======================================

const idiomaGuardado =
    localStorage.getItem("idiomaAdoptaEspacio") || "es";

traducirPagina(idiomaGuardado);

selectorIdioma.addEventListener("change", function () {
    traducirPagina(this.value);
});


